# ==========================================

def get_rule(rule_id: str):
    """Получить правило для участника или администрации."""
    return RULES.get(rule_id) or ADMIN_RULES.get(rule_id)


def get_rule_title(rule_id: str) -> str:
    rule = get_rule(rule_id)
    return rule["title"] if rule else "Неизвестный пункт правил"


def get_penalties(rule_id: str) -> list:
    rule = get_rule(rule_id)
    return rule["penalties"] if rule else []


def get_penalty_options(rule_id: str) -> list:
    """Получить структурированные меры для выбора администратором."""
    rule = RULES.get(rule_id)

    if not rule:
        return []

    return rule.get("penalty_options", [])


def format_rule(rule_id: str) -> str:
    """Подготовить описание правила для уведомления."""
    rule = get_rule(rule_id)

    if not rule:
        return f"Пункт {rule_id}: описание не найдено."

    penalties = "\n".join(
        f"• {penalty}"
        for penalty in rule.get("penalties", [])
    )

    return (
        f"Пункт правил: {rule_id} — {rule['title']}\n\n"
        f"Описание: {rule['description']}\n\n"
        f"Допустимые меры:\n{penalties}"
    )


def is_rule_for_admin(rule_id: str) -> bool:
    """Проверить, относится ли пункт к обязанностям администрации."""
    return rule_id in ADMIN_RULES


def is_exception_to_time_limit(rule_id: str) -> bool:
    """Проверить исключение из общего ограничения в 12 часов."""
    return rule_id in EXCEPTION_RULES
