def get_rule(rule_id: str):
    """Получить описание правила."""
    return RULES.get(rule_id)

def get_rule_title(rule_id: str) -> str:
    """Получить название правила."""
    rule = get_rule(rule_id)
    return rule["title"] if rule else "Неизвестный пункт правил"

def get_penalties(rule_id: str) -> list:
    """Получить допустимые меры наказания."""
    rule = get_rule(rule_id)
    return rule["penalties"] if rule else []

def format_rule(rule_id: str) -> str:
    """Подготовить подробное описание нарушения для уведомления."""
    rule = get_rule(rule_id)
    if not rule:
        return f"Пункт {rule_id}: описание не найдено."

    penalties = "\n".join(
        f"• {penalty}" for penalty in rule["penalties"]
    )

    return (
        f"Пункт правил: {rule_id} — {rule['title']}\n\n"
        f"Описание: {rule['description']}\n\n"
        f"Допустимые меры:\n{penalties}"
    )
