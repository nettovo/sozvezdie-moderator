def remark():
    return {
        "type": "remark",
        "label": "Замечание",
    }


def warning(min_days, max_days=None):
    if max_days is None:
        max_days = min_days

    return {
        "type": "warning",
        "label": "Предупреждение",
        "min_days": min_days,
        "max_days": max_days,
    }


def mute(min_minutes, max_minutes):
    return {
        "type": "mute",
        "label": "Мут",
        "min_minutes": min_minutes,
        "max_minutes": max_minutes,
    }


def ban(permanent=False, manual=False):
    return {
        "type": "ban",
        "label": "Бан",
        "permanent": permanent,
        "requires_manual_assessment": manual,
    }


def require_action(action, label):
    return {
        "type": action,
        "label": label,
        "requires_manual_assessment": True,
        "bot_supported": False,
    }


def manual_measure(label):
    return {
        "type": "manual",
        "label": label,
        "requires_manual_assessment": True,
        "bot_supported": False,
    }


